def _normalize_japanese_for_match(text: str) -> str:
    """表記差（全角/半角、算用/漢数字、句読点・記号）のみを吸収して比較用文字列を作る。"""
    s = unicodedata.normalize("NFKC", str(text or ""))
    s = s.translate(KANJI_DIGIT_MAP)
    s = re.sub(r"[十百千万億兆]+", "", s)
    s = re.sub(r"[\s、。！？・「」『』（）()【】\[\]:：\-—~〜!?,.\'\"…%％¥$円]+", "", s)
    return s.lower()


def _parse_kanji_numeral_token(token: str) -> str:
    if not any(u in token for u in _KANJI_UNIT_VAL):
        return "".join(str(_KANJI_DIGIT_VAL.get(c, c)) for c in token)
    total = 0
    current = 0
    for ch in token:
        if ch in _KANJI_DIGIT_VAL:
            current = _KANJI_DIGIT_VAL[ch]
        elif ch in _KANJI_UNIT_VAL:
            unit = _KANJI_UNIT_VAL[ch]
            total += (1 if current == 0 else current) * unit
            current = 0
    return str(total + current)


def _normalize_cue_text_with_map(raw: str) -> tuple[str, list[int]]:
    chars = list(str(raw or ""))
    norm_chars: list[str] = []
    norm_to_orig: list[int] = []
    i = 0
    while i < len(chars):
        ch = chars[i]
        if ch in _KANJI_DIGIT_VAL or ch in _KANJI_UNIT_VAL:
            start = i
            tok = ""
            while i < len(chars) and (chars[i] in _KANJI_DIGIT_VAL or chars[i] in _KANJI_UNIT_VAL):
                tok += chars[i]
                i += 1
            for d in _parse_kanji_numeral_token(tok):
                norm_chars.append(d)
                norm_to_orig.append(start)
            continue

        nfkc = unicodedata.normalize("NFKC", ch).lower()
        for sub in nfkc:
            if not _CUE_NOISE_RE.match(sub):
                code = ord(sub)
                if 0x30A1 <= code <= 0x30F6:
                    sub = chr(code - 0x60)
                norm_chars.append(sub)
                norm_to_orig.append(i)
        i += 1
    return "".join(norm_chars), norm_to_orig


def _join_shot_subtitles(shot: dict[str, Any]) -> str:
    parts: list[str] = []
    sub = shot.get("subtitle")
    if isinstance(sub, dict):
        parts.append(str(sub.get("line1") or ""))
        parts.append(str(sub.get("line2") or ""))
    for seg in shot.get("subtitleSegments") or []:
        if isinstance(seg, dict):
            parts.append(str(seg.get("line1") or ""))
            parts.append(str(seg.get("line2") or ""))
    return "".join(parts)


def _char_coverage(needle: str, haystack: str) -> float:
    """needle の文字が haystack 内に順番・多重度を緩やかに保ってどれだけ含まれるか（0.0〜1.0）。"""
    if not needle:
        return 1.0
    if not haystack:
        return 0.0
    from collections import Counter

    c_n = Counter(needle)
    c_h = Counter(haystack)
    matched = sum(min(cnt, c_h[ch]) for ch, cnt in c_n.items())
    return matched / max(1, len(needle))


def _estimate_narration_duration_sec(narration_ja: str) -> float:
    text = str(narration_ja or "").strip()
    if not text:
        return 0.0
    try:
        cleaned = sanitize_japanese_text(text)
    except ValueError:
        cleaned = text
    return round(max(0.4, len(cleaned) / EST_READING_CHARS_PER_SEC), 3)


def _resolve_phrase_sec_in_shot(
    phrase: str,
    narration: str,
    subtitle_text: str,
    eval_dur: float,
    tl_shot: dict[str, Any] | None,
) -> float | None:
    """phrase からショット内の推定相対時刻（秒）を解決する（alignment 優先）。"""
    q = str(phrase or "").strip()
    if not q or eval_dur <= 0:
        return None
    q_norm, _ = _normalize_cue_text_with_map(q)

    if isinstance(tl_shot, dict) and isinstance(tl_shot.get("alignment"), dict):
        align = tl_shot["alignment"]
        starts = align.get("charStartSec") or []
        raw_text = str(align.get("text") or "".join(align.get("characters") or []))
        if raw_text and starts:
            exact = raw_text.find(q)
            if 0 <= exact < len(starts):
                return float(starts[exact])
            if q_norm:
                t_norm, t_map = _normalize_cue_text_with_map(raw_text)
                pos = t_norm.find(q_norm)
                if pos < 0 and len(q_norm) >= 2:
                    min_pref = max(2, math.ceil(len(q_norm) * 0.5))
                    for plen in range(len(q_norm) - 1, min_pref - 1, -1):
                        pos = t_norm.find(q_norm[:plen])
                        if pos >= 0:
                            break
                if pos >= 0 and t_map[pos] < len(starts):
                    return float(starts[t_map[pos]])

    for base in (narration, subtitle_text):
        if not base:
            continue
        exact = base.find(q)
        if exact >= 0:
            return round((exact / max(1, len(base))) * eval_dur, 3)
        if q_norm:
            b_norm, _ = _normalize_cue_text_with_map(base)
            if b_norm:
                pos = b_norm.find(q_norm)
                if pos < 0 and len(q_norm) >= 2:
                    min_pref = max(2, math.ceil(len(q_norm) * 0.5))
                    for plen in range(len(q_norm) - 1, min_pref - 1, -1):
                        pos = b_norm.find(q_norm[:plen])
                        if pos >= 0:
                            break
                if pos >= 0:
                    return round((pos / max(1, len(b_norm))) * eval_dur, 3)
    return None


def _detect_real_entities(text: str) -> list[tuple[str, str]]:
    """台本テキストから実在人名候補のみを抽出する（一般名詞の手描き小道具は許容）。"""
    found: list[tuple[str, str]] = []
    seen: set[str] = set()

    for m in KATAKANA_PERSON_RE.finditer(text):
        tok = m.group(0)
        if tok not in seen:
            seen.add(tok)
            found.append((tok, "person"))

    for m in TITLE_PERSON_RE.finditer(text):
        tok = m.group(1)
        if tok not in seen and tok not in {"心理学者", "研究者", "専門家", "科学者"}:
            seen.add(tok)
            found.append((tok, "person"))

    return found


def _extract_balanced_brace_block(text: str, open_brace_idx: int) -> str | None:
    """open_brace_idx ('{') から対応する '}' までの内側文字列を抽出する（文字列・コメント考慮）。"""
    if open_brace_idx < 0 or open_brace_idx >= len(text) or text[open_brace_idx] != "{":
        return None
    n = len(text)
    i = open_brace_idx
    depth = 0
    in_single = False
    in_double = False
    in_line_comment = False
    in_block_comment = False
    template_expr_depths: list[int] = []

    while i < n:
        ch = text[i]
        nxt = text[i + 1] if i + 1 < n else ""

        if in_line_comment:
            if ch == "\n":
                in_line_comment = False
            i += 1
            continue
        if in_block_comment:
            if ch == "*" and nxt == "/":
                in_block_comment = False
                i += 2
                continue
            i += 1
            continue
        if in_single:
            if ch == "\\":
                i += 2
                continue
            if ch == "'":
                in_single = False
            i += 1
            continue
        if in_double:
            if ch == "\\":
                i += 2
                continue
            if ch == '"':
                in_double = False
            i += 1
            continue
        if template_expr_depths and template_expr_depths[-1] == -1:
            # テンプレート文字列リテラル本体内
            if ch == "\\":
                i += 2
                continue
            if ch == "`":
                template_expr_depths.pop()
                i += 1
                continue
            if ch == "$" and nxt == "{":
                template_expr_depths[-1] = depth
                depth += 1
                i += 2
                continue
            i += 1
            continue

        if ch == "/" and nxt == "/":
            in_line_comment = True
            i += 2
            continue
        if ch == "/" and nxt == "*":
            in_block_comment = True
            i += 2
            continue
        if ch == "'":
            in_single = True
            i += 1
            continue
        if ch == '"':
            in_double = True
            i += 1
            continue
        if ch == "`":
            template_expr_depths.append(-1)
            i += 1
            continue

        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if template_expr_depths and template_expr_depths[-1] == depth:
                template_expr_depths[-1] = -1
            if depth == 0:
                return text[open_brace_idx + 1 : i]
        i += 1
    return None


def _split_top_level_object_entries(body: str) -> list[str]:
    entries: list[str] = []
    buf: list[str] = []
    depth_curly = 0
    depth_paren = 0
    depth_bracket = 0
    in_single = False
    in_double = False
    in_backtick = False
    in_line_comment = False
    in_block_comment = False
    i = 0
    n = len(body)

    while i < n:
        ch = body[i]
        nxt = body[i + 1] if i + 1 < n else ""

        if in_line_comment:
            if ch == "\n":
                in_line_comment = False
            i += 1
            continue
        if in_block_comment:
            if ch == "*" and nxt == "/":
                in_block_comment = False
                i += 2
                continue
            i += 1
            continue
        if in_single:
            buf.append(ch)
            if ch == "\\" and i + 1 < n:
                buf.append(body[i + 1])
                i += 2
                continue
            if ch == "'":
                in_single = False
            i += 1
            continue
        if in_double:
            buf.append(ch)
            if ch == "\\" and i + 1 < n:
                buf.append(body[i + 1])
                i += 2
                continue
            if ch == '"':
                in_double = False
            i += 1
            continue
        if in_backtick:
            buf.append(ch)
            if ch == "\\" and i + 1 < n:
                buf.append(body[i + 1])
                i += 2
                continue
            if ch == "`":
                in_backtick = False
            i += 1
            continue

        if ch == "/" and nxt == "/":
            in_line_comment = True
            i += 2
            continue
        if ch == "/" and nxt == "*":
            in_block_comment = True
            i += 2
            continue
        if ch == "'":
            in_single = True
            buf.append(ch)
            i += 1
            continue
        if ch == '"':
            in_double = True
            buf.append(ch)
            i += 1
            continue
        if ch == "`":
            in_backtick = True
            buf.append(ch)
            i += 1
            continue

        if ch == "{":
            depth_curly += 1
        elif ch == "}":
            depth_curly = max(0, depth_curly - 1)
        elif ch == "(":
            depth_paren += 1
        elif ch == ")":
            depth_paren = max(0, depth_paren - 1)
        elif ch == "[":
            depth_bracket += 1
        elif ch == "]":
            depth_bracket = max(0, depth_bracket - 1)

        if ch == "," and depth_curly == 0 and depth_paren == 0 and depth_bracket == 0:
            entries.append("".join(buf))
            buf = []
        else:
            buf.append(ch)
        i += 1

    if buf:
        entries.append("".join(buf))
    return entries


def _extract_object_literal_keys(body: str) -> tuple[set[str], dict[str, str], dict[str, str]]:
    """オブジェクトリテラル本体からトップレベルキー、参照先コンポーネント名、インライン本体を抽出する。"""
    keys: set[str] = set()
    key_to_comp: dict[str, str] = {}
    inline_bodies: dict[str, str] = {}

    for entry in _split_top_level_object_entries(body):
        item = entry.strip()
        if not item or item.startswith("..."):
            continue
        # トップレベルの ':' を探す
        colon_idx = -1
        in_sq = False
        in_dq = False
        for idx, ch in enumerate(item):
            if ch == "'" and not in_dq:
                in_sq = not in_sq
            elif ch == '"' and not in_sq:
                in_dq = not in_dq
            elif ch == ":" and not in_sq and not in_dq:
                colon_idx = idx
                break

        if colon_idx >= 0:
            raw_key = item[:colon_idx].strip()
            rhs = item[colon_idx + 1 :].strip()
        else:
            raw_key = item
            rhs = item

        m_quoted = re.match(r"^(['\"])([^'\"]+)\1$", raw_key)
        m_ident = re.match(r"^([A-Za-z_$][A-Za-z0-9_$]*)$", raw_key)
        if m_quoted:
            k = m_quoted.group(2)
        elif m_ident:
            k = m_ident.group(1)
        else:
            continue

        keys.add(k)
        m_rhs = re.match(r"^([A-Za-z_$][A-Za-z0-9_$]*)(?:\s*$|[,;])", rhs)
        if m_rhs:
            key_to_comp[k] = m_rhs.group(1)
        else:
            inline_bodies[k] = rhs
            m_jsx = re.search(r"<\s*([A-Z][A-Za-z0-9_$]*)\b", rhs)
            if m_jsx:
                key_to_comp[k] = m_jsx.group(1)

    return keys, key_to_comp, inline_bodies


def _find_var_object_open_brace(text: str, var_name: str) -> int | None:
    """`const VAR_NAME (: Type)? = {` の右辺 '{' インデックスを返す（型内の '=>' を避ける）。"""
    pat = re.compile(rf"\b(?:const|let|var)\s+{re.escape(var_name)}\b")
    for m in pat.finditer(text):
        i = m.end()
        n = len(text)
        depth_angle = 0
        depth_paren = 0
        while i < n:
            ch = text[i]
            nxt = text[i + 1] if i + 1 < n else ""
            if ch == "(":
                depth_paren += 1
            elif ch == ")":
                depth_paren = max(0, depth_paren - 1)
            elif ch == "<":
                depth_angle += 1
            elif ch == ">":
                if i > 0 and text[i - 1] == "=":
                    pass
                else:
                    depth_angle = max(0, depth_angle - 1)
            elif ch == "=" and nxt != ">" and depth_paren == 0 and depth_angle == 0:
                j = i + 1
                while j < n and text[j].isspace():
                    j += 1
                if j < n and text[j] == "{":
                    return j
                break
            elif ch == ";" and depth_paren == 0 and depth_angle == 0:
                break
            i += 1
    return None


def _extract_custom_scenes_from_tsx_files(
    scanned_texts: dict[str, str],
) -> tuple[set[str], dict[str, str], dict[str, str], bool]:
    """TSX ディレクトリ全体から customScenes 登録キーとコンポーネント名対応表を抽出する。"""
    registered_keys: set[str] = set()
    key_to_comp: dict[str, str] = {}
    inline_bodies: dict[str, str] = {}
    has_registry = False

    for text in scanned_texts.values():
        for m in re.finditer(r"\bcustomScenes\s*=\s*\{", text):
            has_registry = True
            j = m.end()
            while j < len(text) and text[j].isspace():
                j += 1
            if j < len(text) and text[j] == "{":
                body = _extract_balanced_brace_block(text, j)
                if body is not None:
                    kset, kmap, ibodies = _extract_object_literal_keys(body)
                    registered_keys.update(kset)
                    key_to_comp.update(kmap)
                    inline_bodies.update(ibodies)
                continue

            m_var = re.match(r"([A-Za-z_$][A-Za-z0-9_$]*)\s*\}", text[j:])
            if m_var:
                var_name = m_var.group(1)
                for target_text in scanned_texts.values():
                    open_idx = _find_var_object_open_brace(target_text, var_name)
                    if open_idx is not None:
                        body = _extract_balanced_brace_block(target_text, open_idx)
                        if body is not None:
                            kset, kmap, ibodies = _extract_object_literal_keys(body)
                            registered_keys.update(kset)
                            key_to_comp.update(kmap)
                            inline_bodies.update(ibodies)
                        break

    return registered_keys, key_to_comp, inline_bodies, has_registry


def _extract_component_body(scanned_texts: dict[str, str], symbol_name: str) -> str | None:
    """TSX ファイル群から指定シンボル定義付近のソース断片を抽出する。"""
    if not symbol_name:
        return None
    pat = re.compile(rf"\b(?:const|function)\s+{re.escape(symbol_name)}\b")
    for text in scanned_texts.values():
        m = pat.search(text)
        if not m:
            continue
        start = m.start()
        rest = text[m.end() :]
        nxt = re.search(r"\n(?:export\s+)?(?:const|function|interface|type)\s+[A-Za-z_]", rest)
        end = m.end() + (nxt.start() if nxt else min(len(rest), 4500))
        return text[start:end]
    return None


def _strip_ts_comments(text: str) -> str:
    """文字列リテラルを保護したまま TS/JSX の行コメント・ブロックコメントを空白へ置換する。"""
    out: list[str] = []
    i = 0
    n = len(text)
    in_sq = False
    in_dq = False
    in_bt = False
    while i < n:
        ch = text[i]
        nxt = text[i + 1] if i + 1 < n else ""
        if in_sq:
            out.append(ch)
            if ch == "\\" and i + 1 < n:
                out.append(text[i + 1])
                i += 2
                continue
            if ch == "'":
                in_sq = False
            i += 1
            continue
        if in_dq:
            out.append(ch)
            if ch == "\\" and i + 1 < n:
                out.append(text[i + 1])
                i += 2
                continue
            if ch == '"':
                in_dq = False
            i += 1
            continue
        if in_bt:
            out.append(ch)
            if ch == "\\" and i + 1 < n:
                out.append(text[i + 1])
                i += 2
                continue
            if ch == "`":
                in_bt = False
            i += 1
            continue
        if ch == "/" and nxt == "/":
            out.extend("  ")
            i += 2
            while i < n and text[i] != "\n":
                out.append(" ")
                i += 1
            continue
        if ch == "/" and nxt == "*":
            out.extend("  ")
            i += 2
            while i < n:
                if text[i] == "*" and (i + 1 < n and text[i + 1] == "/"):
                    out.extend("  ")
                    i += 2
                    break
                out.append("\n" if text[i] == "\n" else " ")
                i += 1
            continue
        if ch == "'":
            in_sq = True
        elif ch == '"':
            in_dq = True
        elif ch == "`":
            in_bt = True
        out.append(ch)
        i += 1
    return "".join(out)


def _find_jsx_open_tag_end(text: str, after_name_idx: int) -> tuple[int, bool] | None:
    """JSX 開始タグの属性部（{...} と文字列を保護）を読み飛ばし、(終端'>'の次idx, 自己閉じか) を返す。"""
    i = after_name_idx
    n = len(text)
    depth_brace = 0
    in_sq = False
    in_dq = False
    in_bt = False
    while i < n:
        ch = text[i]
        nxt = text[i + 1] if i + 1 < n else ""
        if in_sq:
            if ch == "\\":
                i += 2
                continue
            if ch == "'":
                in_sq = False
            i += 1
            continue
        if in_dq:
            if ch == "\\":
                i += 2
                continue
            if ch == '"':
                in_dq = False
            i += 1
            continue
        if in_bt:
            if ch == "\\":
                i += 2
                continue
            if ch == "`":
                in_bt = False
            i += 1
            continue
        if ch == "'":
            in_sq = True
        elif ch == '"':
            in_dq = True
        elif ch == "`":
            in_bt = True
        elif ch == "{":
            depth_brace += 1
        elif ch == "}":
            depth_brace = max(0, depth_brace - 1)
        elif depth_brace == 0:
            if ch == "/" and nxt == ">":
                return i + 2, True
            if ch == ">":
                return i + 1, False
            if ch == "<":
                return None
        i += 1
    return None


def _find_matching_jsx_close_tag(
    text: str, tag_name: str, body_start: int
) -> tuple[int, int] | None:
    """body_start 以降でネストを辿り、対応する </tag_name> の (開始idx, 終了後idx) を返す。"""
    pat = re.compile(rf"<(?:/\s*{re.escape(tag_name)}\s*>|{re.escape(tag_name)}(?=[\s/>]))")
    depth = 1
    pos = body_start
    while pos < len(text):
        m = pat.search(text, pos)
        if not m:
            return None
        if text[m.start() + 1] == "/":
            depth -= 1
            if depth == 0:
                return m.start(), m.end()
            pos = m.end()
        else:
            opened = _find_jsx_open_tag_end(text, m.end())
            if opened is None:
                pos = m.end()
                continue
            open_end, self_closing = opened
            if not self_closing:
                depth += 1
            pos = open_end
    return None


def _iter_jsx_elements(
    clean_text: str,
    target_tags: tuple[str, ...],
) -> list[tuple[str, str, int, int, str]]:
    """指定タグ名の (tag_name, attrs, body_start, body_end, body) 一覧を返す。自己閉じ時は body=''。"""
    alt = "|".join(re.escape(t) for t in sorted(target_tags, key=len, reverse=True))
    pat = re.compile(rf"<({alt})(?=[\s/>])")
    results: list[tuple[str, str, int, int, str]] = []
    pos = 0
    while pos < len(clean_text):
        m = pat.search(clean_text, pos)
        if not m:
            break
        tag_name = m.group(1)
        opened = _find_jsx_open_tag_end(clean_text, m.end())
        if opened is None:
            pos = m.end()
            continue
        open_end, self_closing = opened
        attrs_end = open_end - (2 if self_closing else 1)
        attrs = clean_text[m.end() : attrs_end]
        if self_closing:
            results.append((tag_name, attrs, open_end, open_end, ""))
            pos = open_end
            continue
        matched_close = _find_matching_jsx_close_tag(clean_text, tag_name, open_end)
        if matched_close is None:
            pos = open_end
            continue
        close_start, _close_end = matched_close
        results.append((tag_name, attrs, open_end, close_start, clean_text[open_end:close_start]))
        pos = open_end
    return results


def _strip_crisp_blocks(body: str) -> str:
    """Stage 本体内で明示的に非ボイル化された <Stage.Crisp>...</Stage.Crisp> を除外する。"""
    spans = _iter_jsx_elements(body, ("Stage.Crisp",))
    if not spans:
        return body
    out = list(body)
    for _t, _a, b_start, b_end, _b in spans:
        for idx in range(b_start, b_end):
            out[idx] = " "
    return "".join(out)


def _is_long_screen_text(raw: str) -> bool:
    """画面内の表示文字として長文傾向（視認性・引き算規律違反の目安）かを判定する。"""
    compact = re.sub(r"\s+", "", str(raw or ""))
    if not compact:
        return False
    return len(compact) >= MAX_ON_SCREEN_SHORT_TEXT_CHARS or (
        "。" in compact and len(compact) > 20
    )


def _extract_tsx_scene_detail(
    scanned_texts: dict[str, str],
    scene_key: str,
    key_to_comp: dict[str, str],
    inline_bodies: dict[str, str] | None = None,
) -> tuple[bool, list[str], list[float], int]:
    """TSX シーン関数本体から (見つかったか, cue文言一覧, 数値at/from/triggerSec, 動的イベント数) を抽出する。"""
    comp_name = key_to_comp.get(scene_key) or scene_key
    body = _extract_component_body(scanned_texts, comp_name)
    if body is None and comp_name != scene_key:
        body = _extract_component_body(scanned_texts, scene_key)
    if body is None and inline_bodies:
        body = inline_bodies.get(scene_key)
    if body is None:
        return False, [], [], 0

    cue_phrases = [m.group(2) for m in re.finditer(r"\bcue\(\s*(['\"])([^'\"]+)\1", body)]
    num_times: list[float] = []
    for m in re.finditer(r"\b(?:at|from|triggerSec)\s*(?:=|\:)\s*\{?\s*([0-9]+(?:\.[0-9]+)?)\s*\}?", body):
        try:
            num_times.append(float(m.group(1)))
        except ValueError:
            pass

    total_event_calls = len(re.findall(r"\b(?:cue\(|(?:at|from|triggerSec)\s*(?:=|\:))", body))
    return True, cue_phrases, num_times, total_event_calls


def _extract_tsx_scene_timing_info(
    scanned_texts: dict[str, str],
    scene_key: str,
    key_to_comp: dict[str, str],
    inline_bodies: dict[str, str] | None = None,
) -> tuple[list[str], list[float], int]:
    """TSX シーン関数本体から cue("..."), 数値 at/from/triggerSec, 動的イベント数を抽出する。"""
    _found, cue_phrases, num_times, total_event_calls = _extract_tsx_scene_detail(
        scanned_texts, scene_key, key_to_comp, inline_bodies
    )
    return cue_phrases, num_times, total_event_calls


def audit_stickman_collage_tsx_dir(tsx_dir: Path) -> ValidationReport:
    """stickman_collage 用 TSX ディレクトリの静的監査（SaaS禁止CSS・出典・ID・シーン登録・素材参照＋引き算規律WARNING）。"""
    rep = ValidationReport()
    if not tsx_dir.is_dir():
        rep.errors.append(f"TSX directory not found: {tsx_dir}")
        return rep

    saas_dark_hits = 0
    border_left_hits = 0
    pill_radius_hits = 0
    slate_color_hits = 0
    clip_cards_hits = 0
    citation_hits = 0
    bad_comp_ids = 0
    text_in_boil_warnings = 0
    long_text_warnings = 0
    tiny_visual_warnings = 0
    sfx_cue_count = 0
    scanned: list[str] = []
    scanned_texts: dict[str, str] = {}
    resolved_assets_in_tsx: list[tuple[str, str]] = []
    manual_eyecatch_files: list[str] = []
    legacy_eyecatch_overlay_files: list[str] = []

    for fp in sorted(list(tsx_dir.glob("*.ts")) + list(tsx_dir.glob("*.tsx"))):
        if fp.name in _SKIP_TSX_FILES:
            continue
        text = fp.read_text(encoding="utf-8")
        if text.lstrip().startswith(_AUTO_GEN_HEADER):
            continue
        scanned.append(fp.name)
        scanned_texts[fp.name] = text
        clean_text = _strip_ts_comments(text)

        dark_matches = _SAAS_DARK_RE.findall(clean_text)
        if dark_matches:
            saas_dark_hits += len(dark_matches)
            rep.errors.append(
                f"TSX SaaSダークUIカード色を検出 ({fp.name}: {len(dark_matches)}箇所): "
                "stickman_collage コンポーネント / アナログ紙色を使用してください。"
            )

        bl_matches = _BORDER_LEFT_RE.findall(clean_text)
        if bl_matches:
            border_left_hits += len(bl_matches)
            rep.errors.append(
                f"TSX borderLeft アクセント帯 (SaaS/パワポ風カード) を検出 ({fp.name}: {len(bl_matches)}箇所)。"
            )

        pr_matches = _PILL_RADIUS_RE.findall(clean_text)
        if pr_matches:
            pill_radius_hits += len(pr_matches)
            rep.errors.append(
                f"TSX borderRadius: 999 ピル型UIを検出 ({fp.name}: {len(pr_matches)}箇所): "
                "マスキングテープ・手描き付箋・HandDrawnFrame を使用してください。"
            )

        slate_matches = _SLATE_HEX_RE.findall(clean_text)
        if slate_matches:
            slate_color_hits += len(slate_matches)
            rep.errors.append(
                f"TSX Tailwind slate 系グレー ({sorted(set(slate_matches))}) を検出 ({fp.name}): "
                "鉛筆・黒鉛・紙インク色（theme.mutedInk 等）を使用してください。"
            )

        cc_matches = _CLIP_CARDS_TSX_RE.findall(clean_text)
        if cc_matches:
            clip_cards_hits += len(cc_matches)
            rep.errors.append(
                f"TSX 廃止済み variant='clip_cards' を検出 ({fp.name}): "
                "'paper_notes' / 'formula' / 自由TSX演出へ置換してください。"
            )

        cit_matches = _CITATION_TSX_RE.findall(clean_text)
        if cit_matches:
            citation_hits += len(cit_matches)
            rep.errors.append(
                f"TSX 画面内出典表示ハードコード検出 ({fp.name}): 出典は概要欄のみに集約してください。"
            )

        for m in re.finditer(r"<Composition[^>]*\bid\s*=\s*[\"']([^\"']+)[\"']", clean_text):
            cid = m.group(1)
            if "_" in cid or not COMPOSITION_ID_RE.match(cid):
                bad_comp_ids += 1
                rep.errors.append(
                    f"TSX Remotion Composition ID に禁止文字('_'等)を検出 ({fp.name}): {cid!r} "
                    "(英数字とハイフン '-' のみ使用可)。"
                )

        for m in _RESOLVE_ASSET_RE.finditer(clean_text):
            resolved_assets_in_tsx.append((m.group(2), fp.name))

        if _MANUAL_EYECATCH_JSX_RE.search(clean_text):
            manual_eyecatch_files.append(fp.name)
        if _LEGACY_EYECATCH_OVERLAY_RE.search(clean_text):
            legacy_eyecatch_overlay_files.append(fp.name)

        # --- 共通 <SfxCue> 配置数と kind 妥当性チェック ---
        for _tag_name, attrs, _bs, _be, _body in _iter_jsx_elements(clean_text, ("SfxCue",)):
            sfx_cue_count += 1
            m_kind = re.search(r"\bkind\s*=\s*(?:\{\s*)?(['\"`])([^'\"`]+)\1", attrs)
            if m_kind:
                kind_lit = m_kind.group(2).strip()
                try:
                    resolve_sfx_kind(kind_lit)
                except ValueError:
                    rep.errors.append(
                        f"TSX <SfxCue> に未登録の kind={kind_lit!r} を検出 ({fp.name}): "
                        "標準20種またはカスタム WAV は src=... を使用してください。"
                    )

        # --- 引き算規律 WARNING 1: ボイル適用範囲内での <text> / <HandText> / <SvgStamp> 配置 ---
        boil_text_offsets: set[int] = set()
        for tag_name, attrs, body_start, _body_end, body in _iter_jsx_elements(
            clean_text, ("BoilSvg", "Stage.Boil", "Stage", "g")
        ):
            if not body:
                continue
            if tag_name == "g":
                if not re.search(r"\bfilter\s*=\s*\{[^}]*boil", attrs, re.IGNORECASE):
                    continue
            elif tag_name == "Stage":
                if re.search(r"\bmanualLayers\b", attrs):
                    continue
            effective_body = _strip_crisp_blocks(body) if tag_name == "Stage" else body
            for tm in _TEXT_IN_BOIL_RE.finditer(effective_body):
                boil_text_offsets.add(body_start + tm.start())
        if boil_text_offsets:
            text_in_boil_warnings += len(boil_text_offsets)
            rep.warnings.append(
                f"TSX ボイル適用範囲内に文字要素 (<text> / <HandText> / <SvgStamp>) を {len(boil_text_offsets)}箇所検出 ({fp.name}): "
                "文字・スタンプは <Stage crisp={...}> / <Stage.Crisp> 等の非ボイル層へ分離してください。"
            )

        # --- 引き算規律 WARNING 2: 画面内長文テキスト傾向 ---
        for tag_name, attrs, _bs, _be, body in _iter_jsx_elements(
            clean_text, ("text", *sorted(_TEXT_COMPONENT_PROP_NAMES))
        ):
            candidate = ""
            if tag_name == "text" and body:
                stripped_b = body.strip()
                m_lit = re.match(r"^\{\s*(['\"`])([^'\"`]+)\1\s*\}$", stripped_b)
                if m_lit:
                    candidate = m_lit.group(2)
                elif "<" not in stripped_b and "{" not in stripped_b:
                    candidate = stripped_b
            elif tag_name in _TEXT_COMPONENT_PROP_NAMES:
                m_tp = _TEXT_PROP_LITERAL_RE.search(attrs)
                if m_tp:
                    candidate = m_tp.group(2)
            if candidate and _is_long_screen_text(candidate):
                long_text_warnings += 1
                preview = re.sub(r"\s+", "", candidate)[:22]
                rep.warnings.append(
                    f"TSX 画面内長文テキスト傾向を検出 ({fp.name}: {preview!r}...): "
                    "画面内文字は短いキーワード・ラベルへ引き算することを推奨します。"
                )

            if tag_name in _TEXT_COMPONENT_PROP_NAMES:
                m_sz = _SIZE_PROP_LITERAL_RE.search(attrs)
                if m_sz:
                    sz = float(m_sz.group(1))
                    if 0.0 < sz < MIN_MOBILE_FONT_SIZE_PX:
                        tiny_visual_warnings += 1
                        rep.warnings.append(
                            f"TSX スマホ視認性低下の恐れがある極小 size={sz:g} (< {MIN_MOBILE_FONT_SIZE_PX:g}) を検出 ({fp.name})。"
                        )

        # --- 引き算規律 WARNING 4: スマホ視認性の極小 fontSize / スケール ---
        for m in _FONT_SIZE_LITERAL_RE.finditer(clean_text):
            val = float(m.group(1) or m.group(2))
            if 0.0 < val < MIN_MOBILE_FONT_SIZE_PX:
                tiny_visual_warnings += 1
                rep.warnings.append(
                    f"TSX スマホ視認性低下の恐れがある極小 fontSize={val:g} (< {MIN_MOBILE_FONT_SIZE_PX:g}) を検出 ({fp.name})。"
                )

        for m in _SCALE_FUNC_LITERAL_RE.finditer(clean_text):
            vals = [float(m.group(1))]
            if m.group(2) is not None:
                vals.append(float(m.group(2)))
            if any(0.0 < v < MIN_MOBILE_STATIC_SCALE for v in vals):
                tiny_visual_warnings += 1
                rep.warnings.append(
                    f"TSX 極小スケール {m.group(0)} (< {MIN_MOBILE_STATIC_SCALE}) を検出 ({fp.name}): "
                    "スマホ視聴時の視認性確認を推奨します。"
                )

        for m in _SCALE_PROP_LITERAL_RE.finditer(clean_text):
            val = float(m.group(1))
            if 0.0 < val < MIN_MOBILE_STATIC_SCALE:
                tiny_visual_warnings += 1
                rep.warnings.append(
                    f"TSX 極小スケール scale={{{val:g}}} (< {MIN_MOBILE_STATIC_SCALE}) を検出 ({fp.name}): "
                    "スマホ視聴時の視認性確認を推奨します。"
                )

    registered_keys, key_to_comp, inline_bodies, has_registry = _extract_custom_scenes_from_tsx_files(scanned_texts)

    rep.metrics = {
        "tsx_scanned_files": scanned,
        "tsx_saas_dark_card_hits": saas_dark_hits,
        "tsx_border_left_hits": border_left_hits,
        "tsx_pill_radius_hits": pill_radius_hits,
        "tsx_slate_color_hits": slate_color_hits,
        "tsx_clip_cards_hits": clip_cards_hits,
        "tsx_citation_hits": citation_hits,
        "tsx_invalid_composition_ids": bad_comp_ids,
        "tsx_text_in_boil_warnings": text_in_boil_warnings,
        "tsx_long_text_warnings": long_text_warnings,
        "tsx_tiny_visual_warnings": tiny_visual_warnings,
        "tsx_sfx_cue_count": sfx_cue_count,
        "tsx_has_custom_scenes_registry": has_registry,
        "tsx_registered_scene_keys": sorted(registered_keys),
        "tsx_key_to_component": key_to_comp,
        "tsx_resolved_asset_ids": resolved_assets_in_tsx,
        "tsx_manual_eyecatch_files": sorted(set(manual_eyecatch_files)),
        "tsx_legacy_eyecatch_overlay_files": sorted(set(legacy_eyecatch_overlay_files)),
        "_tsx_scanned_texts": scanned_texts,
        "_tsx_inline_bodies": inline_bodies,
    }
    return rep


def _collect_shot_beat_indices(sh: dict[str, Any]) -> list[tuple[str, int]]:
    out: list[tuple[str, int]] = []

    def _walk(obj: Any, path: str) -> None:
        if isinstance(obj, dict):
            for k, v in obj.items():
                if (k == "beatIndex" or k.endswith("BeatIndex") or k == "handNoteBeat") and isinstance(
                    v, (int, float)
                ) and not isinstance(v, bool):
                    out.append((f"{path}.{k}", int(v)))
                else:
                    _walk(v, f"{path}.{k}")
        elif isinstance(obj, list):
            for idx, item in enumerate(obj):
                _walk(item, f"{path}[{idx}]")

    for field_name in ("photoLayer", "diagram", "stickFigures", "callout", "stamp"):
        if sh.get(field_name) is not None:
            _walk(sh[field_name], field_name)
    return out


def _collect_visual_events_and_max_gap(
    sh: dict[str, Any],
    eval_dur: float,
    tl_shot: dict[str, Any] | None,
    tsx_scanned_texts: dict[str, str] | None,
    tsx_key_to_comp: dict[str, str] | None,
    tsx_inline_bodies: dict[str, str] | None = None,
) -> tuple[float, list[float]]:
    if eval_dur <= 0.05:
        return 0.0, [0.0]

    narr = str(sh.get("narrationJa") or "")
    sub_text = _join_shot_subtitles(sh)
    events: list[float] = [0.0]

    def _add(t: float) -> None:
        if math.isfinite(t) and 0.0 <= t <= eval_dur:
            events.append(round(t, 4))

    tl_start = float(tl_shot["startSec"]) if isinstance(tl_shot, dict) and tl_shot.get("startSec") is not None else None
    has_tl_beats = isinstance(tl_shot, dict) and isinstance(tl_shot.get("beatTimesSec"), list) and len(tl_shot["beatTimesSec"]) > 0
    if has_tl_beats and tl_shot is not None:
        for bt in tl_shot["beatTimesSec"]:
            if isinstance(bt, (int, float)) and tl_start is not None:
                _add(float(bt) - tl_start)
    else:
        for bobj in sh.get("beats") or []:
            if not isinstance(bobj, dict):
                continue
            if bobj.get("timeSec") is not None:
                _add(float(bobj["timeSec"]))
            elif bobj.get("offsetSec") is not None:
                _add(float(bobj["offsetSec"]))
            elif bobj.get("phraseJa"):
                pt = _resolve_phrase_sec_in_shot(
                    str(bobj["phraseJa"]), narr, sub_text, eval_dur, tl_shot
                )
                if pt is not None:
                    _add(pt)

    pl = sh.get("photoLayer")
    if isinstance(pl, dict) and pl.get("triggerOffsetSec") is not None:
        _add(float(pl["triggerOffsetSec"]))
    for fig in sh.get("stickFigures") or []:
        if isinstance(fig, dict) and fig.get("triggerOffsetSec") is not None:
            _add(float(fig["triggerOffsetSec"]))
    for key in ("callout", "stamp"):
        obj = sh.get(key)
        if isinstance(obj, dict) and obj.get("triggerOffsetSec") is not None:
            _add(float(obj["triggerOffsetSec"]))

    diag = sh.get("diagram")
    if isinstance(diag, dict):
        kind = diag.get("kind")
        params = diag.get("params") or {}
        if isinstance(params, dict):
            if kind == "staggered_grid":
                st = float(params.get("startOffsetSec") or 0.1)
                span = float(params.get("spanSec") or max(1.2, min(2.6, eval_dur - 0.6)))
                cur = st
                while cur <= min(eval_dur, st + span):
                    _add(cur)
                    cur += 1.0
            elif kind == "ruler_gauge":
                _add(0.15)
                _add(0.6)
                _add(min(eval_dur, 1.45))
            elif kind == "newspaper_card":
                hl_d = float(params.get("highlightDelaySec") or 0.4)
                hl_dur = float(params.get("highlightDurationSec") or 0.55)
                _add(hl_d)
                _add(min(eval_dur, hl_d + hl_dur))

            for seq_key in ("bars", "items", "nodes", "cards", "leftItems", "rightItems"):
                seq = params.get(seq_key)
                if not isinstance(seq, list):
                    continue
                for idx, entry in enumerate(seq):
                    if not isinstance(entry, dict):
                        continue
                    for tf in ("at", "triggerSec", "crossedOutAt"):
                        val = entry.get(tf)
                        if isinstance(val, (int, float)):
                            rel_v = float(val) - tl_start if (tl_start is not None and float(val) >= tl_start) else float(val)
                            _add(rel_v)
                    if entry.get("at") is None and entry.get("triggerSec") is None and entry.get("beatIndex") is None:
                        _add(min(eval_dur, 0.15 + idx * 0.5))

    scene = sh.get("scene")
    dynamic_tsx_events = 0
    if isinstance(scene, dict) and scene.get("mode") == "tsx" and tsx_scanned_texts is not None:
        comp_key = str(scene.get("component") or "")
        cue_phrases, num_times, total_calls = _extract_tsx_scene_timing_info(
            tsx_scanned_texts, comp_key, tsx_key_to_comp or {}, tsx_inline_bodies
        )
        dynamic_tsx_events = total_calls
        for ph in cue_phrases:
            pt = _resolve_phrase_sec_in_shot(ph, narr, sub_text, eval_dur, tl_shot)
            if pt is not None:
                _add(pt)
        for nt in num_times:
            _add(nt)

    pts = sorted(set(events))
    pts.append(round(eval_dur, 4))
    max_gap = max((pts[i + 1] - pts[i] for i in range(len(pts) - 1)), default=0.0)

    # TSX 側が動的表現で cue/at を複数使っているのにリテラル展開できなかった場合のみ安全側補正
    if (
        isinstance(scene, dict)
        and scene.get("mode") == "tsx"
        and len(pts) <= 2
        and dynamic_tsx_events >= 2
        and (eval_dur / dynamic_tsx_events) <= MAX_VISUAL_STATIC_GAP_SEC
    ):
        max_gap = round(eval_dur / dynamic_tsx_events, 3)

    return round(max_gap, 3), pts


def resolve_chapter_eyecatch_spec(chapter: dict[str, Any]) -> dict[str, Any] | None:
    """chapter.eyecatch を正規化して返す。未指定または enabled=False なら None。"""
    raw = chapter.get("eyecatch")
    if not isinstance(raw, dict):
        return None
    if raw.get("enabled") is False:
        return None
    variant = str(raw.get("variant") or DEFAULT_EYECATCH_VARIANT)
    show_name = bool(raw.get("showName", True))
    with_sfx = bool(raw.get("withSfx", True))
    sfx_volume = float(raw["sfxVolume"]) if isinstance(raw.get("sfxVolume"), (int, float)) and not isinstance(raw.get("sfxVolume"), bool) else 1.0
    lead_in_sec = (
        float(raw["leadInSec"])
        if isinstance(raw.get("leadInSec"), (int, float)) and not isinstance(raw.get("leadInSec"), bool)
        else BUGURU_EYECATCH_DEFAULT_LEAD_IN_SEC
    )
    duration_sec = (
        float(raw["durationSec"])
        if isinstance(raw.get("durationSec"), (int, float)) and not isinstance(raw.get("durationSec"), bool)
        else BUGURU_EYECATCH_DURATION_SEC
    )
    post_pause_sec = (
        float(raw["postPauseSec"])
        if isinstance(raw.get("postPauseSec"), (int, float)) and not isinstance(raw.get("postPauseSec"), bool)
        else BUGURU_EYECATCH_DEFAULT_POST_PAUSE_SEC
    )
    return {
        "variant": variant,
        "showName": show_name,
        "withSfx": with_sfx,
        "sfxVolume": round(sfx_volume, 4),
        "leadInSec": round(lead_in_sec, 4),
        "durationSec": round(duration_sec, 4),
        "postPauseSec": round(post_pause_sec, 4),
    }


def _validate_chapter_eyecatch_spec(
    ch: dict[str, Any],
    ch_idx: int,
    rep: ValidationReport,
) -> dict[str, Any] | None:
    """Spec の chapter.eyecatch フィールドを契約検証し、有効なら正規化辞書を返す。"""
    raw = ch.get("eyecatch")
    if raw is None:
        return None
    if not isinstance(raw, dict):
        rep.errors.append(f"Chapter {ch_idx}.eyecatch must be an object or null.")
        return None
    if raw.get("enabled") is False:
        return None

    variant = raw.get("variant")
    if variant is not None and str(variant) not in ALLOWED_EYECATCH_VARIANTS:
        rep.errors.append(
            f"Chapter {ch_idx}.eyecatch.variant must be one of {sorted(ALLOWED_EYECATCH_VARIANTS)}, got: {variant!r}"
        )
    for bkey in ("showName", "withSfx", "enabled"):
        if raw.get(bkey) is not None and not isinstance(raw.get(bkey), bool):
            rep.errors.append(f"Chapter {ch_idx}.eyecatch.{bkey} must be boolean, got: {raw.get(bkey)!r}")
    if raw.get("showName") is False:
        rep.warnings.append(
            f"Chapter {ch_idx}.eyecatch.showName is false. ch1 公式運用は全章転換で showName: true 統一を推奨。"
        )

    sfx_vol = raw.get("sfxVolume")
    if sfx_vol is not None:
        if not isinstance(sfx_vol, (int, float)) or isinstance(sfx_vol, bool) or not (0.0 <= float(sfx_vol) <= 2.0):
            rep.errors.append(f"Chapter {ch_idx}.eyecatch.sfxVolume must be 0.0〜2.0, got: {sfx_vol!r}")

    lead_in = raw.get("leadInSec")
    if lead_in is not None:
        if (
            not isinstance(lead_in, (int, float))
            or isinstance(lead_in, bool)
            or not (0.0 <= float(lead_in) <= BUGURU_EYECATCH_MAX_LEAD_IN_SEC)
        ):
            rep.errors.append(
                f"Chapter {ch_idx}.eyecatch.leadInSec must be 0.0〜{BUGURU_EYECATCH_MAX_LEAD_IN_SEC:.1f}s, got: {lead_in!r}"
            )

    dur = raw.get("durationSec")
    if dur is not None:
        if not isinstance(dur, (int, float)) or isinstance(dur, bool) or not (0.5 <= float(dur) <= 3.0):
            rep.errors.append(f"Chapter {ch_idx}.eyecatch.durationSec must be 0.5〜3.0s, got: {dur!r}")

    post_pause = raw.get("postPauseSec")
    if post_pause is not None:
        if (
            not isinstance(post_pause, (int, float))
            or isinstance(post_pause, bool)
            or float(post_pause) < BUGURU_EYECATCH_MIN_POST_PAUSE_SEC
            or float(post_pause) > BUGURU_EYECATCH_MAX_POST_PAUSE_SEC
        ):
            rep.errors.append(
                f"Chapter {ch_idx}.eyecatch.postPauseSec must be "
                f"{BUGURU_EYECATCH_MIN_POST_PAUSE_SEC:.2f}〜{BUGURU_EYECATCH_MAX_POST_PAUSE_SEC:.1f}s "
                f"(アイキャッチ完全終了後の自然な無音間を確保すること), got: {post_pause!r}"
            )

    return resolve_chapter_eyecatch_spec(ch)


def _validate_subtitle_sync(timeline: dict[str, Any], rep: ValidationReport) -> None:
    cues = timeline.get("subtitles")
    if cues is None:  # 部分タイムラインも検査対象にできる。
        return
    tolerance = 1 / max(1, timeline.get("fps") or 30)
    for shot in timeline.get("shots", []):
        if not shot.get("alignment"):
            continue
        try:
            expected = aligned_subtitles(shot)
            actual = [cue for cue in cues if shot["startSec"] <= cue["startSec"] < shot["endSec"]]
            if len(actual) != len(expected):
                raise ValueError("字幕の枚数が一致しません")
            for cue, target in zip(actual, expected):
                if any(abs(cue[key] - target[key]) > tolerance for key in ("startSec", "endSec")):
                    raise ValueError(f"{target['line1']!r} の表示区間が発話時刻と一致しません")
        except (KeyError, ValueError, TypeError) as exc:
            rep.errors.append(f"{shot.get('chunkId')}: 字幕同期: {exc}")


def _validate_timeline_eyecatch_contracts(
    spec_eyecatch_by_chapter: dict[int, dict[str, Any]],
    timeline: dict[str, Any],
    rep: ValidationReport,
) -> None:
    """timeline.json 上の章間アイキャッチ無音スロット・前後章＆字幕非重複契約を機械検証する。"""
    tl_chapters = [c for c in (timeline.get("chapters") or []) if isinstance(c, dict)]
    tl_shots = [s for s in (timeline.get("shots") or []) if isinstance(s, dict)]
    tl_subs = [s for s in (timeline.get("subtitles") or []) if isinstance(s, dict)]

    tl_chapter_by_idx: dict[int, dict[str, Any]] = {}
    for tc in tl_chapters:
        if tc.get("chapterIndex") is not None:
            tl_chapter_by_idx[int(tc["chapterIndex"])] = tc

    # Spec に eyecatch がある章は timeline 側にも eyecatch 区間が必須（chapters を含む timeline のみ検証）
    if "chapters" in timeline:
        for ch_idx in sorted(spec_eyecatch_by_chapter):
            tc = tl_chapter_by_idx.get(ch_idx)
            if not tc or not isinstance(tc.get("eyecatch"), dict):
                rep.errors.append(
                    f"Chapter {ch_idx}: spec.chapters[].eyecatch が定義されていますが "
                    "timeline.chapters[].eyecatch が未生成です（build_stickman_collage_assets.py で再ビルドしてください）。"
                )

    # timeline 内の全アイキャッチ区間について、無音間・非重複を厳格検証
    for tc in tl_chapters:
        ec = tc.get("eyecatch")
        if not isinstance(ec, dict):
            continue
        ch_idx = int(tc.get("chapterIndex", 0))
        variant = str(ec.get("variant") or "")
        if variant not in ALLOWED_EYECATCH_VARIANTS:
            rep.errors.append(
                f"Chapter {ch_idx}: timeline.eyecatch.variant must be one of {sorted(ALLOWED_EYECATCH_VARIANTS)}, got: {variant!r}"
            )

        raw_start = ec.get("startSec")
        raw_end = ec.get("endSec")
        raw_dur = ec.get("durationSec")
        if not all(isinstance(v, (int, float)) and not isinstance(v, bool) for v in (raw_start, raw_end, raw_dur)):
            rep.errors.append(f"Chapter {ch_idx}: timeline.eyecatch の startSec/endSec/durationSec が不正です。")
            continue
        ec_start = float(raw_start)
        ec_end = float(raw_end)
        ec_dur = float(raw_dur)
        if ec_start < 0.0 or ec_end <= ec_start or ec_dur <= 0.0:
            rep.errors.append(
                f"Chapter {ch_idx}: timeline.eyecatch 区間が不正です (start={ec_start:.3f}s, end={ec_end:.3f}s, dur={ec_dur:.3f}s)。"
            )
            continue
        if abs((ec_end - ec_start) - ec_dur) > 0.02:
            rep.errors.append(
                f"Chapter {ch_idx}: timeline.eyecatch の endSec-startSec ({ec_end - ec_start:.3f}s) が "
                f"durationSec ({ec_dur:.3f}s) と一致しません。"
            )

        # 次章（この章）開始時刻と後間の検証
        ch_shots = [s for s in tl_shots if int(s.get("chapterIndex", -1)) == ch_idx and s.get("startSec") is not None]
        first_shot_start = min((float(s["startSec"]) for s in ch_shots), default=None)
        tc_start = float(tc["startSec"]) if isinstance(tc.get("startSec"), (int, float)) else None
        next_start = first_shot_start if first_shot_start is not None else tc_start

        if next_start is None:
            rep.errors.append(f"Chapter {ch_idx}: timeline に次章の開始時刻が見つかりません。")
            continue

        spec_ec = spec_eyecatch_by_chapter.get(ch_idx)
        min_required_pause = BUGURU_EYECATCH_MIN_POST_PAUSE_SEC
        if spec_ec is not None:
            min_required_pause = max(min_required_pause, float(spec_ec["postPauseSec"]) - 0.02)

        actual_post_pause = next_start - ec_end
        if actual_post_pause < min_required_pause - 1e-3:
            rep.errors.append(
                f"Chapter {ch_idx}: アイキャッチ終了 ({ec_end:.3f}s) 〜次章開始 ({next_start:.3f}s) の無音間が "
                f"{actual_post_pause:.3f}s しかなく契約下限 ({min_required_pause:.2f}s) 未満です。"
                "アイキャッチ完全終了＋自然な間を置いてから次章を開始してください。"
            )
        if tc_start is not None and tc_start < ec_end + BUGURU_EYECATCH_MIN_POST_PAUSE_SEC - 1e-3:
            rep.errors.append(
                f"Chapter {ch_idx}: timeline.chapters.startSec ({tc_start:.3f}s) がアイキャッチ終了+後間 "
                f"({ec_end + BUGURU_EYECATCH_MIN_POST_PAUSE_SEC:.3f}s) より前に始まっています。"
            )

        # 前章の終了時刻がアイキャッチ開始に食い込んでいないか
        prev_chapters = [c for c in tl_chapters if int(c.get("chapterIndex", 0)) < ch_idx and c.get("endSec") is not None]
        if prev_chapters:
            prev_ch = max(prev_chapters, key=lambda c: int(c.get("chapterIndex", 0)))
            prev_end = float(prev_ch["endSec"])
            if prev_end > ec_start + 1e-3:
                rep.errors.append(
                    f"Chapter {ch_idx}: 前章 (Chapter {prev_ch.get('chapterIndex')}) の終了 ({prev_end:.3f}s) が "
                    f"アイキャッチ開始 ({ec_start:.3f}s) に重複しています。"
                )

        # アイキャッチ本体＋後間 [ec_start, next_start) に食い込むショットを禁止
        intermission_end = max(ec_end, next_start)
        for sh in tl_shots:
            if sh.get("startSec") is None or sh.get("endSec") is None:
                continue
            s0 = float(sh["startSec"])
            s1 = float(sh["endSec"])
            if s0 < intermission_end - 1e-3 and s1 > ec_start + 1e-3:
                rep.errors.append(
                    f"Chapter {ch_idx}: ショット {sh.get('chunkId')!r} [{s0:.3f}s, {s1:.3f}s] が "
                    f"アイキャッチ無音区間 [{ec_start:.3f}s, {intermission_end:.3f}s] と重複しています。"
                )

        # アイキャッチ本体＋後間 [ec_start, next_start) に食い込む字幕を禁止
        for sub_idx, sub in enumerate(tl_subs):
            if sub.get("startSec") is None or sub.get("endSec") is None:
                continue
            u0 = float(sub["startSec"])
            u1 = float(sub["endSec"])
            if u0 < intermission_end - 1e-3 and u1 > ec_start + 1e-3:
                rep.errors.append(
                    f"Chapter {ch_idx}: 字幕[{sub_idx}] ({sub.get('line1')!r}) [{u0:.3f}s, {u1:.3f}s] が "
                    f"アイキャッチ無音区間 [{ec_start:.3f}s, {intermission_end:.3f}s] と重複しています。"
                )


def _extract_media_backdrop_asset_id(raw: Any) -> tuple[str | None, str | None]:
    """shot.mediaBackdrop（assetId 文字列または設定オブジェクト）から assetId を抽出する。"""
    if raw is None:
        return None, None
    if isinstance(raw, str):
        return raw.strip(), None
    if isinstance(raw, dict):
        aid = raw.get("assetId")
        if isinstance(aid, str):
            return aid.strip(), None
        return "", None
    return None, "mediaBackdrop must be an assetId string or an object with assetId."


def validate_stickman_collage_spec(
    spec: dict[str, Any],
    *,
    tsx_dir: Path | None = None,
    timeline: dict[str, Any] | None = None,
) -> ValidationReport:
    """stickman_collage Spec JSON（＋任意 TSX / timeline.json）を契約検証する。"""
    rep = ValidationReport()
    if not isinstance(spec, dict):
        rep.errors.append("Spec root must be a JSON object.")
        return rep

    for req_key in ("slug", "compositionId", "title", "formatId", "video", "chapters", "tts", "audio", "legalChecklist"):
        if req_key not in spec:
            rep.errors.append(f"Missing required top-level field: {req_key}")

    # TSX 事前監査（シーン登録キー・resolveAsset・SaaS禁止パターンを先に抽出）
    tsx_rep: ValidationReport | None = None
    registered_tsx_scenes: set[str] = set()
    tsx_resolved_assets: list[tuple[str, str]] = []
    tsx_scanned_texts: dict[str, str] | None = None
    tsx_key_to_comp: dict[str, str] | None = None
    tsx_inline_bodies: dict[str, str] | None = None
    tsx_manual_eyecatch_files: list[str] = []
    tsx_legacy_eyecatch_overlay_files: list[str] = []
    if tsx_dir is not None:
        tsx_rep = audit_stickman_collage_tsx_dir(tsx_dir)
        rep.errors.extend(tsx_rep.errors)
        rep.warnings.extend(tsx_rep.warnings)
        registered_tsx_scenes = set(tsx_rep.metrics.get("tsx_registered_scene_keys") or [])
        tsx_resolved_assets = list(tsx_rep.metrics.get("tsx_resolved_asset_ids") or [])
        tsx_scanned_texts = tsx_rep.metrics.get("_tsx_scanned_texts")
        tsx_key_to_comp = tsx_rep.metrics.get("tsx_key_to_component")
        tsx_inline_bodies = tsx_rep.metrics.get("_tsx_inline_bodies")
        tsx_manual_eyecatch_files = list(tsx_rep.metrics.get("tsx_manual_eyecatch_files") or [])
        tsx_legacy_eyecatch_overlay_files = list(tsx_rep.metrics.get("tsx_legacy_eyecatch_overlay_files") or [])

    # timeline.json ショット辞書
    timeline_shots_by_id: dict[str, dict[str, Any]] = {}
    if isinstance(timeline, dict):
        for tl_sh in timeline.get("shots") or []:
            if isinstance(tl_sh, dict) and tl_sh.get("chunkId"):
                timeline_shots_by_id[str(tl_sh["chunkId"])] = tl_sh

    # 1. formatId & Remotion Composition ID（_ 禁止）
    fmt = str(spec.get("formatId") or "")
    low_fmt = fmt.lower()
    if "plan_d" in low_fmt or "pland" in low_fmt or "3d" in low_fmt:
        rep.errors.append(f"Prohibited heavy 3D formatId: {fmt!r}")
    elif fmt != "stickman_collage":
        rep.errors.append(f"formatId must be 'stickman_collage', got: {fmt!r}")

    comp_id = str(spec.get("compositionId") or "")
    if not comp_id:
        rep.errors.append("compositionId must be non-empty.")
    elif "_" in comp_id or not COMPOSITION_ID_RE.match(comp_id):
        rep.errors.append(
            f"compositionId contains prohibited '_' or non-alphanumeric chars: {comp_id!r} "
            "(Remotion ID は英数字とハイフン '-' のみ許可)."
        )

    # 2. 解像度・90%セーフゾーン契約
    video = spec.get("video")
    if isinstance(video, dict):
        if video.get("width") != 1920 or video.get("height") != 1080 or video.get("fps") != 30:
            rep.errors.append(
                f"video must be 1920x1080@30fps, got: {video.get('width')}x{video.get('height')}@{video.get('fps')}"
            )
        smx = video.get("safeMarginX")
        smy = video.get("safeMarginY")
        if smx is not None and (not isinstance(smx, (int, float)) or float(smx) < 96):
            rep.errors.append(f"video.safeMarginX must be >= 96 (90% safe zone), got: {smx!r}")
        if smy is not None and (not isinstance(smy, (int, float)) or float(smy) < 54):
            rep.errors.append(f"video.safeMarginY must be >= 54 (90% safe zone), got: {smy!r}")

    # 3. 法務・フォント（SIL OFL / Apache 2.0限定）
    legal = spec.get("legalChecklist")
    if isinstance(legal, dict):
        sources = legal.get("primarySources") or []
        if not isinstance(sources, list) or len(sources) < 3:
            rep.errors.append("legalChecklist.primarySources must contain at least 3 primary sources.")
        if legal.get("usesAcmlVoiceForCriticism") is not False:
            rep.errors.append("legalChecklist.usesAcmlVoiceForCriticism must be false.")
        if legal.get("usesAiExpertAdvice") is not False:
            rep.errors.append("legalChecklist.usesAiExpertAdvice must be false.")
        fonts_lic = str(legal.get("fontsLicense") or "")
        low_fl = fonts_lic.lower()
        if any(tok in low_fl for tok in FORBIDDEN_FONT_TOKENS):
            rep.errors.append(f"Forbidden non-OFL font in fontsLicense: {fonts_lic!r}")
        if "sil ofl" not in low_fl and "apache" not in low_fl:
            rep.errors.append(f"legalChecklist.fontsLicense must declare SIL OFL / Apache 2.0, got: {fonts_lic!r}")

    # 4. TTS モデル・禁止モデル検証
    tts = spec.get("tts")
    if isinstance(tts, dict):
        prov = str(tts.get("provider") or "").lower()
        if prov and prov not in {"elevenlabs", "gemini", "auto"}:
            rep.errors.append(f"Unsupported tts.provider: {prov!r}")
        for m in tts.get("models") or []:
            if any(tok in str(m).lower() for tok in FORBIDDEN_MODEL_TOKENS):
                rep.errors.append(f"Forbidden/retired TTS model specified: {m!r}")

    # 5. 音響契約（合成ピアノ廃止）
    audio = spec.get("audio")
    if isinstance(audio, dict):
        mode = str(audio.get("mode") or "")
        if mode not in ALLOWED_AUDIO_MODES:
            rep.errors.append(f"audio.mode must be one of {sorted(ALLOWED_AUDIO_MODES)}, got: {mode!r}")
        audio_blob = repr(audio).lower()
        for tok in PROHIBITED_AUDIO_TOKENS:
            if tok in audio_blob:
                rep.errors.append(
                    f"Prohibited audio token {tok!r} detected in audio config "
                    "(合成ピアノ・合成BGM・Suno/Udio自動挿入は廃止済み)."
                )
        if mode == "licensed_bgm_file":
            if not str(audio.get("bgmFile") or "").strip():
                rep.errors.append("audio.bgmFile is required when audio.mode == 'licensed_bgm_file'.")
            if not str(audio.get("bgmLicenseNote") or "").strip():
                rep.errors.append("audio.bgmLicenseNote is required when audio.mode == 'licensed_bgm_file'.")

    # 6. オプション endCta（enabled: false / null / 省略時はスルー）
    end_cta = spec.get("endCta")
    if isinstance(end_cta, dict) and end_cta.get("enabled", True) is not False:
        if end_cta.get("hasFinalizingPhrase") is not False:
            rep.errors.append("endCta.hasFinalizingPhrase must be false when endCta is enabled.")
        edur = end_cta.get("durationSec")
        if edur is not None and (not isinstance(edur, (int, float)) or not (5.0 <= float(edur) <= 10.0)):
            rep.errors.append(f"endCta.durationSec must be 5.0〜10.0s, got: {edur!r}")
        for txt in (
            str(end_cta.get("headlineJa") or ""),
            str(end_cta.get("narrationJa") or ""),
            _join_shot_subtitles({"subtitle": end_cta.get("subtitle")}),
        ):
            for phrase in FORBIDDEN_FINALIZING_PHRASES:
                if phrase in txt:
                    rep.errors.append(f"endCta contains prohibited finalizing phrase: {phrase!r}")

    # 7. assetCatalog 検証（AI画像生成完全禁止）
    catalog = spec.get("assetCatalog")
    if catalog is None:
        catalog = []
    if not isinstance(catalog, list):
        rep.errors.append("assetCatalog must be a list.")
        catalog = []

    catalog_by_id: dict[str, dict[str, Any]] = {}
    for idx, item in enumerate(catalog):
        if not isinstance(item, dict):
            rep.errors.append(f"assetCatalog[{idx}] must be an object.")
            continue
        aid = item.get("id")
        if not aid or not isinstance(aid, str):
            rep.errors.append(f"assetCatalog[{idx}] missing valid id.")
            continue
        if aid in catalog_by_id:
            rep.errors.append(f"Duplicate assetCatalog id: {aid!r}")
        catalog_by_id[aid] = item
        if not item.get("src"):
            rep.errors.append(f"assetCatalog[{idx}] ({aid}) missing src.")
        blob = " ".join(
            str(item.get(k) or "") for k in ("kind", "license", "src", "cutoutSrc", "creditShort", "sourceUrl")
        ).lower()
        for tok in PROHIBITED_AI_IMAGE_TOKENS:
            if tok in blob:
                rep.errors.append(
                    f"assetCatalog[{idx}] ({aid}) contains prohibited AI image token {tok!r} "
                    "(AI画像生成は動画・サムネイルともに全面不使用)."
                )

    used_asset_ids: set[str] = set()
    for tsx_aid, tsx_fname in tsx_resolved_assets:
        if tsx_aid not in catalog_by_id:
            rep.errors.append(f"TSX ({tsx_fname}): resolveAsset({tsx_aid!r}) が assetCatalog に未登録です。")
        else:
            used_asset_ids.add(tsx_aid)

    # 8. チャプター＆ショット検証
    chapters = spec.get("chapters") or []
    if not isinstance(chapters, list) or len(chapters) == 0:
        rep.errors.append("chapters must be a non-empty list.")
        return rep

    seen_chunk_ids: set[str] = set()
    polarity_seq: list[str] = []
    backdrop_seq: list[str] = []
    polarity_durations: list[tuple[str, float]] = []
    backdrop_durations: list[tuple[str, float]] = []
    total_sfx = 0
    tsx_scene_shots = 0
    media_backdrop_shots = 0
    max_static_gap_sec = 0.0
    spec_long_text_warnings = 0
    low_cue_density_warnings = 0
    body_shots: list[dict[str, Any]] = []
    spec_eyecatch_by_chapter: dict[int, dict[str, Any]] = {}

    for ch in chapters:
        if not isinstance(ch, dict):
            rep.errors.append("Each chapter must be an object.")
            continue
        ch_idx = int(ch.get("chapterIndex", 0))
        resolved_ec = _validate_chapter_eyecatch_spec(ch, ch_idx, rep)
        if resolved_ec is not None:
            spec_eyecatch_by_chapter[ch_idx] = resolved_ec
        for sh in ch.get("shots") or []:
            if not isinstance(sh, dict):
                rep.errors.append(f"Chapter {ch_idx} contains non-object shot.")
                continue
            cid = str(sh.get("chunkId") or f"shot_{sh.get('shotIndex')}")
            if cid in seen_chunk_ids:
                rep.errors.append(f"Duplicate chunkId: {cid!r}")
            seen_chunk_ids.add(cid)

            tl_sh = timeline_shots_by_id.get(cid)
            narr = str(sh.get("narrationJa") or "")
            est_dur = _estimate_narration_duration_sec(narr)

            # targetDurationSec は任意（10秒上限エラーは廃止）。指定時は > 0 のみ要求。
            raw_target_dur = sh.get("targetDurationSec")
            target_dur: float | None = None
            if raw_target_dur is not None:
                try:
                    target_dur = float(raw_target_dur)
                except (TypeError, ValueError):
                    rep.errors.append(f"{cid}: targetDurationSec must be numeric, got: {raw_target_dur!r}")
                else:
                    if target_dur <= 0.0:
                        rep.errors.append(f"{cid}: targetDurationSec must be > 0.")

            actual_dur: float | None = None
            if isinstance(tl_sh, dict) and tl_sh.get("startSec") is not None and tl_sh.get("endSec") is not None:
                actual_dur = max(0.05, float(tl_sh["endSec"]) - float(tl_sh["startSec"]))

            eval_dur = actual_dur if actual_dur is not None else max(est_dur, target_dur or 0.0)
            beat_bound_dur = actual_dur if actual_dur is not None else (target_dur if target_dur and target_dur > 0 else est_dur)

            pol = str(sh.get("polarity") or "")
            if pol not in ALLOWED_POLARITIES:
                rep.errors.append(f"{cid}: invalid polarity {pol!r} (allowed: {sorted(ALLOWED_POLARITIES)}).")
            else:
                if sh.get("lightBg") is not None:
                    lb = bool(sh["lightBg"])
                    if pol in DARK_POLARITIES and lb:
                        rep.errors.append(f"{cid}: lightBg={sh['lightBg']!r} contradicts polarity={pol!r}.")
                    elif pol in LIGHT_POLARITIES and not lb:
                        rep.errors.append(f"{cid}: lightBg={sh['lightBg']!r} contradicts polarity={pol!r}.")

            # scene（TSX シーン入口）検証
            scene = sh.get("scene")
            is_tsx_scene = False
            if scene is not None:
                if not isinstance(scene, dict):
                    rep.errors.append(f"{cid}: scene must be an object.")
                else:
                    s_mode = str(scene.get("mode") or "preset")
                    if s_mode not in ALLOWED_SCENE_MODES:
                        rep.errors.append(f"{cid}: invalid scene.mode {s_mode!r} (allowed: {sorted(ALLOWED_SCENE_MODES)}).")
                    elif s_mode == "tsx":
                        is_tsx_scene = True
                        tsx_scene_shots += 1
                        comp_key = str(scene.get("component") or "").strip()
                        if not comp_key:
                            rep.errors.append(f"{cid}: scene.mode=='tsx' ですが scene.component が未指定です。")
                        elif tsx_dir is not None and comp_key not in registered_tsx_scenes:
                            rep.errors.append(
                                f"{cid}: 未登録の TSX シーンキー {comp_key!r} (customScenes に登録されていません)."
                            )
                    scene_aids = scene.get("assetIds")
                    if scene_aids is not None:
                        if not isinstance(scene_aids, list):
                            rep.errors.append(f"{cid}: scene.assetIds must be a list.")
                        else:
                            for s_aid in scene_aids:
                                aid_str = str(s_aid or "")
                                if not aid_str or aid_str not in catalog_by_id:
                                    rep.errors.append(f"{cid}: scene.assetIds {aid_str!r} not found in assetCatalog.")
                                else:
                                    used_asset_ids.add(aid_str)

            arch = str(sh.get("layoutArchetype") or "")
            if is_tsx_scene:
                if arch and arch not in ALLOWED_LAYOUT_ARCHETYPES:
                    rep.errors.append(f"{cid}: invalid layoutArchetype {arch!r}.")
            else:
                if arch not in ALLOWED_LAYOUT_ARCHETYPES:
                    rep.errors.append(f"{cid}: invalid layoutArchetype {arch!r}.")

            # 画面内出典禁止チェック
            if sh.get("showOnScreenCitation") is True:
                rep.errors.append(f"{cid}: showOnScreenCitation=true is prohibited (出典は概要欄集約).")

            # 死にフィールド警告
            if sh.get("secondaryPhotoLayers"):
                rep.warnings.append(
                    f"{cid}: 'secondaryPhotoLayers' は描画されない旧フィールド（非推奨）です。"
                    "photoLayer / scene.assetIds / cards[].assetId を使用してください。"
                )

            # diagram 検証（clip_cards・badge/subText 禁止＋図解内素材ID解決）
            diag = sh.get("diagram")
            if isinstance(diag, dict):
                diag_kind = str(diag.get("kind") or "")
                params = diag.get("params") or {}
                if isinstance(params, dict):
                    if params.get("citation"):
                        rep.errors.append(f"{cid}: diagram.params.citation is prohibited (出典は概要欄集約).")

                    if diag_kind == "kinetic_list":
                        if params.get("variant") == "clip_cards":
                            rep.errors.append(
                                f"{cid}: kinetic_list variant='clip_cards' (SaaS風3段バー) は廃止されました。"
                                "'paper_notes' または 'formula'、あるいは scene.mode='tsx' を使用してください。"
                            )
                        for k_idx, k_item in enumerate(params.get("items") or []):
                            if isinstance(k_item, dict) and (k_item.get("badge") or k_item.get("subText")):
                                rep.errors.append(
                                    f"{cid}: kinetic_list.items[{k_idx}] の badge / subText (SaaS風装飾) は廃止されました。"
                                )

                    for p_key in ("imageAssetId", "assetId"):
                        if params.get(p_key):
                            aid_str = str(params[p_key])
                            if aid_str not in catalog_by_id:
                                rep.errors.append(f"{cid}: diagram.params.{p_key} {aid_str!r} not found in assetCatalog.")
                            else:
                                used_asset_ids.add(aid_str)

                    if isinstance(params.get("cards"), list):
                        for c_idx, card in enumerate(params["cards"]):
                            if isinstance(card, dict) and card.get("assetId"):
                                aid_str = str(card["assetId"])
                                if aid_str not in catalog_by_id:
                                    rep.errors.append(
                                        f"{cid}: diagram.params.cards[{c_idx}].assetId {aid_str!r} not found in assetCatalog."
                                    )
                                else:
                                    used_asset_ids.add(aid_str)

            # ナレーション＆禁止語＆AI構文
            if narr.strip():
                try:
                    sanitize_japanese_text(narr)
                except ValueError as exc:
                    rep.errors.append(f"{cid}: {exc}")
            for phrase in FORBIDDEN_FINALIZING_PHRASES:
                if phrase in narr:
                    rep.errors.append(f"{cid}: prohibited finalizing phrase {phrase!r}")
            for phrase in FORBIDDEN_AI_PHRASES:
                if phrase in narr:
                    rep.errors.append(f"{cid}: prohibited AI slop phrase {phrase!r}")

            # 字幕 18文字上限・孤立文字・一言一句一致検証
            sub_objs: list[dict[str, Any]] = []
            if isinstance(sh.get("subtitle"), dict):
                sub_objs.append(sh["subtitle"])
            for seg in sh.get("subtitleSegments") or []:
                if isinstance(seg, dict):
                    sub_objs.append(seg)

            if narr.strip() and not sub_objs:
                rep.errors.append(f"{cid}: narrationJa is non-empty but subtitle / subtitleSegments is missing.")

            for sub in sub_objs:
                l1 = str(sub.get("line1") or "")
                l2 = str(sub.get("line2") or "")
                for lk, lv in (("line1", l1), ("line2", l2)):
                    if lv and len(lv) > 18:
                        rep.errors.append(f"{cid}.subtitle.{lk} exceeds 18 chars ({len(lv)}): {lv!r}")
                    if "出典:" in lv or "出典：" in lv:
                        rep.warnings.append(f"{cid}.subtitle.{lk} contains '出典': 画面内出典は概要欄集約を推奨。")
                if l2 and len(l2.strip()) == 1:
                    rep.warnings.append(f"{cid}.subtitle.line2 is a single orphan character ({l2!r}): 改行位置調整を推奨。")

            if narr.strip() and sub_objs:
                norm_narr = _normalize_japanese_for_match(narr)
                norm_sub = _normalize_japanese_for_match(_join_shot_subtitles(sh))
                if norm_narr:
                    len_ratio = len(norm_sub) / max(1, len(norm_narr))
                    cov = _char_coverage(norm_narr, norm_sub)
                    if len_ratio < 0.55 or len_ratio > 1.65 or cov < 0.45:
                        rep.errors.append(
                            f"{cid}: 字幕とナレーションの一言一句一致違反 (len_ratio={len_ratio:.2f}, coverage={cov:.2f}). "
                            "要約・単語削除・言い換えは禁止です。"
                        )
                    elif len_ratio < 0.72 or cov < 0.62:
                        rep.warnings.append(
                            f"{cid}: 字幕とナレーションに乖離傾向 (len_ratio={len_ratio:.2f}, coverage={cov:.2f})."
                        )

            co = sh.get("callout")
            if isinstance(co, dict) and co.get("textJa"):
                ct = str(co["textJa"])
                if "出典:" in ct or "出典：" in ct:
                    rep.warnings.append(f"{cid}: callout contains '出典': 画面内出典は原則禁止。")
                if _is_long_screen_text(ct):
                    spec_long_text_warnings += 1
                    rep.warnings.append(
                        f"{cid}: callout.textJa が長文傾向 ({len(ct)}字): "
                        "画面内文字は短いキーワードへ引き算することを推奨します。"
                    )

            hand_note_val = sh.get("handNote")
            if isinstance(hand_note_val, str) and _is_long_screen_text(hand_note_val):
                spec_long_text_warnings += 1
                rep.warnings.append(
                    f"{cid}: handNote が長文傾向 ({len(hand_note_val)}字): "
                    "画面内文字は短い注釈へ引き算することを推奨します。"
                )

            for fig_idx, fig in enumerate(sh.get("stickFigures") or []):
                if isinstance(fig, dict) and isinstance(fig.get("bubbleTextJa"), str):
                    bt_txt = re.sub(r"\s+", "", fig["bubbleTextJa"])
                    if len(bt_txt) >= MAX_BUBBLE_TEXT_CHARS:
                        spec_long_text_warnings += 1
                        rep.warnings.append(
                            f"{cid}.stickFigures[{fig_idx}].bubbleTextJa が長文傾向 ({len(bt_txt)}字): "
                            "吹き出し台詞の短縮を推奨します。"
                        )

            # 拍＆SFX 範囲外チェック
            raw_beats = sh.get("beats") or []
            if beat_bound_dur > 0.0:
                for b_idx_pos, bobj in enumerate(raw_beats):
                    if not isinstance(bobj, dict):
                        continue
                    rel_t = bobj.get("timeSec") if bobj.get("timeSec") is not None else bobj.get("offsetSec")
                    if rel_t is not None:
                        rv = float(rel_t)
                        if rv < 0.0 or rv > beat_bound_dur + 1e-4:
                            rep.errors.append(
                                f"{cid}.beats[{b_idx_pos}]: 拍時刻 {rv:.2f}s がショット尺範囲 [0, {beat_bound_dur:.2f}s] 外です。"
                            )

            for path_label, b_ref_idx in _collect_shot_beat_indices(sh):
                if b_ref_idx < 0 or (len(raw_beats) > 0 and b_ref_idx >= len(raw_beats)):
                    rep.errors.append(
                        f"{cid}.{path_label}: beatIndex={b_ref_idx} が beats 範囲 [0, {max(0, len(raw_beats) - 1)}] 外です。"
                    )

            if isinstance(tl_sh, dict) and tl_sh.get("startSec") is not None and tl_sh.get("endSec") is not None:
                tl_s = float(tl_sh["startSec"])
                tl_e = float(tl_sh["endSec"])
                for bt in tl_sh.get("beatTimesSec") or []:
                    if isinstance(bt, (int, float)):
                        btf = float(bt)
                        if btf < tl_s - 0.05 or btf > tl_e + 0.05:
                            rep.errors.append(
                                f"{cid}: timeline.beatTimesSec={btf:.2f}s がショット区間 [{tl_s:.2f}s, {tl_e:.2f}s] 外です。"
                            )

            for sfx_idx, sfx in enumerate(sh.get("sfx") or []):
                if not isinstance(sfx, dict):
                    continue
                skind = str(sfx.get("kind") or "")
                try:
                    resolve_sfx_kind(skind)
                except ValueError:
                    rep.errors.append(f"{cid}: unsupported sfx kind {skind!r}")
                else:
                    total_sfx += 1
                if sfx.get("offsetSec") is not None and beat_bound_dur > 0.0:
                    sv = float(sfx["offsetSec"])
                    if sv < 0.0 or sv > beat_bound_dur + 1e-4:
                        rep.errors.append(
                            f"{cid}.sfx[{sfx_idx}]: SFX offsetSec={sv:.2f}s がショット尺範囲 [0, {beat_bound_dur:.2f}s] 外です。"
                        )

            # photoLayer / mediaBackdrop 素材参照記録（secondaryPhotoLayers は死にフィールドにつき除外）
            pl = sh.get("photoLayer")
            if isinstance(pl, dict) and pl.get("assetId"):
                aid = str(pl["assetId"])
                if aid not in catalog_by_id:
                    rep.errors.append(f"{cid}: photoLayer.assetId {aid!r} not found in assetCatalog.")
                else:
                    used_asset_ids.add(aid)

            mb = sh.get("mediaBackdrop")
            mb_aid: str | None = None
            if mb is not None:
                extracted_aid, mb_type_err = _extract_media_backdrop_asset_id(mb)
                if mb_type_err:
                    rep.errors.append(f"{cid}: {mb_type_err}")
                elif not extracted_aid or extracted_aid not in catalog_by_id:
                    rep.errors.append(f"{cid}: mediaBackdrop assetId {extracted_aid!r} not found in assetCatalog.")
                else:
                    used_asset_ids.add(extracted_aid)
                    mb_aid = extracted_aid
                    media_backdrop_shots += 1

            is_end_cta = sh.get("narrativeRole") == "end_cta" or arch == "end_cta"
            if not is_end_cta:
                # 実尺ベース「視覚イベント無変化 > 4.5秒」警告
                max_gap, _ = _collect_visual_events_and_max_gap(
                    sh, eval_dur, tl_sh, tsx_scanned_texts, tsx_key_to_comp, tsx_inline_bodies
                )
                max_static_gap_sec = max(max_static_gap_sec, max_gap)
                if max_gap > MAX_VISUAL_STATIC_GAP_SEC:
                    rep.warnings.append(
                        f"{cid}: 推定/実尺 {eval_dur:.2f}s 内で視覚イベント無変化区間が {max_gap:.2f}s "
                        f"(> {MAX_VISUAL_STATIC_GAP_SEC:.1f}s) あります。"
                    )

                # cue() 低密度（長時間無同期）WARNING
                if is_tsx_scene and tsx_scanned_texts is not None and isinstance(scene, dict):
                    scene_comp_key = str(scene.get("component") or "").strip()
                    comp_found, cue_phrases, _nt, _tc = _extract_tsx_scene_detail(
                        tsx_scanned_texts,
                        scene_comp_key,
                        tsx_key_to_comp or {},
                        tsx_inline_bodies,
                    )
                    if comp_found:
                        if eval_dur >= 4.0 and len(cue_phrases) == 0:
                            low_cue_density_warnings += 1
                            rep.warnings.append(
                                f"{cid}: TSX シーン {scene_comp_key!r} (尺 {eval_dur:.2f}s) で cue() 呼び出しが 0 回です"
                                "（語単位の実音声同期を推奨）。"
                            )
                        elif eval_dur >= 6.0 and len(cue_phrases) > 0 and (eval_dur / len(cue_phrases)) > MAX_CUE_INTERVAL_SEC:
                            low_cue_density_warnings += 1
                            avg_sec = eval_dur / len(cue_phrases)
                            rep.warnings.append(
                                f"{cid}: TSX シーン {scene_comp_key!r} の cue() 密度が低めです"
                                f"（{len(cue_phrases)}回 / {eval_dur:.2f}s, 平均 {avg_sec:.2f}s/回 > {MAX_CUE_INTERVAL_SEC:.1f}s）。"
                            )

                # Hero ショットの TSX 演出推奨警告
                is_hero = sh.get("narrativeRole") in HERO_NARRATIVE_ROLES or sh.get("comicPunchline") is True
                if is_hero and not is_tsx_scene:
                    rep.warnings.append(
                        f"{cid}: Hero ショット (role={sh.get('narrativeRole')}) ですが scene.mode='tsx' が未設定です。"
                        "TSX 自由演出の活用を推奨します。"
                    )

                body_shots.append(sh)
                if pol in ALLOWED_POLARITIES:
                    polarity_seq.append(pol)
                    backdrop_key = f"media:{mb_aid}" if mb_aid else f"polarity:{pol}"
                    backdrop_seq.append(backdrop_key)
                    dur_for_pol = eval_dur if eval_dur > 0 else float(target_dur or 0.0)
                    if polarity_durations and polarity_durations[-1][0] == pol:
                        prev_p, prev_d = polarity_durations[-1]
                        polarity_durations[-1] = (prev_p, prev_d + dur_for_pol)
                    else:
                        polarity_durations.append((pol, dur_for_pol))
                    if backdrop_durations and backdrop_durations[-1][0] == backdrop_key:
                        prev_b, prev_bd = backdrop_durations[-1]
                        backdrop_durations[-1] = (prev_b, prev_bd + dur_for_pol)
                    else:
                        backdrop_durations.append((backdrop_key, dur_for_pol))

    if len(body_shots) == 0:
        rep.errors.append("No body shots found in chapters.")
        return rep

    # 8.5 章間アイキャッチのタイムライン無音間契約＆TSX二重配置/旧重ね掛け検出
    if isinstance(timeline, dict):
        _validate_subtitle_sync(timeline, rep)
        _validate_timeline_eyecatch_contracts(spec_eyecatch_by_chapter, timeline, rep)

    if spec_eyecatch_by_chapter and tsx_manual_eyecatch_files:
        rep.errors.append(
            f"TSX ({', '.join(tsx_manual_eyecatch_files)}): spec.chapters[].eyecatch 定義と手動 <BuguruEyecatch> 配置が重複しています。"
            "StickmanCollageTemplate が自動描画するため TSX 側の手動配置を削除してください。"
        )
    elif not spec_eyecatch_by_chapter and tsx_legacy_eyecatch_overlay_files:
        rep.warnings.append(
            f"TSX ({', '.join(tsx_legacy_eyecatch_overlay_files)}): 旧重ね掛け方式 (- BUGURU_EYECATCH_CUT_SEC) を検出しました。"
            "アイキャッチ再生中に次章ナレーション・字幕・シーンが被るため、新規エピソードでは spec.chapters[].eyecatch 専用無音スロット方式を使用してください。"
        )

    tsx_sfx_cue_count = int(tsx_rep.metrics.get("tsx_sfx_cue_count", 0)) if tsx_rep is not None else 0
    if tsx_rep is not None and total_sfx == 0 and tsx_sfx_cue_count == 0:
        rep.warnings.append(
            "Spec sfx および TSX <SfxCue> がともに 0 件です (視覚ヒットフレームへの <SfxCue> 配置を推奨)."
        )

    # 9. 全編単一背景 Warning ＆ 背景切替リズムチェック
    unique_polarities = set(polarity_seq)
    polarity_switches = max(0, len(polarity_durations) - 1)
    unique_backdrops = set(backdrop_seq)
    backdrop_switches = max(0, len(backdrop_durations) - 1)
    if len(unique_backdrops) <= 1 or backdrop_switches == 0:
        rep.warnings.append(
            f"全編が単一背景 ({sorted(unique_backdrops)}) で切替回数が 0 回です。"
            "公式8種背景（black / white_sketch / grid_paper / wood_desk / kraft_cork / blueprint / cream_notebook / light_table）や mediaBackdrop（実写動画・画像背景）の切替を織り交ぜて視聴疲労を防いでください。"
        )
    elif sum(d for _, d in backdrop_durations) >= 24.0:
        for idx_bd, (b_name, b_dur) in enumerate(backdrop_durations):
            if 0 < idx_bd < len(backdrop_durations) - 1 and b_dur < 3.5:
                rep.warnings.append(
                    f"背景ブロック #{idx_bd + 1} ({b_name}) が {b_dur:.1f}s と短すぎます（フラッシュノイズ防止のため最低4秒以上推奨）。"
                )

    # 10. 固有の実在物（実在人名・特定場所・固有資料/商品）の実写素材紐づけチェック
    real_targets = spec.get("realAssetTargets") or []
    covered_target_terms: list[str] = []
    if not isinstance(real_targets, list):
        rep.errors.append("realAssetTargets must be a list when specified.")
        real_targets = []

    for idx, tgt in enumerate(real_targets):
        if not isinstance(tgt, dict):
            rep.errors.append(f"realAssetTargets[{idx}] must be an object.")
            continue
        label = str(tgt.get("labelJa") or "").strip()
        cat = str(tgt.get("category") or "")
        aid = tgt.get("assetId")
        allow_fb = bool(tgt.get("allowHandDrawnFallback", False))
        reason = str(tgt.get("reasonIfOmitted") or "").strip()
        covered_target_terms.append(label)

        if aid:
            if aid not in catalog_by_id:
                rep.errors.append(f"realAssetTargets[{idx}] ({label}): assetId {aid!r} not found in assetCatalog.")
            else:
                item_kind = str(catalog_by_id[aid].get("kind") or "")
                if cat == "person" and item_kind not in {"person_photo", "photo_cutout"}:
                    rep.warnings.append(
                        f"realAssetTargets[{idx}] ({label}): person 対象は assetCatalog.kind='person_photo' を推奨 (got {item_kind!r})."
                    )
                if aid not in used_asset_ids:
                    rep.warnings.append(
                        f"realAssetTargets[{idx}] ({label}): assetId {aid!r} がどのショットにも配置されていません。"
                    )
        else:
            if cat in REQUIRED_PHOTO_TARGET_CATEGORIES:
                if allow_fb:
                    detail = f" ({reason})" if reason else ""
                    rep.warnings.append(
                        f"realAssetTargets[{idx}] ({label}): 固有実在対象 ({cat}) が実写未紐づけです{detail}。"
                    )
                else:
                    rep.errors.append(
                        f"realAssetTargets[{idx}] ({label}): 固有の実在物 ({cat}) は実写/資料 assetId の紐づけが必須です。"
                    )
            elif not allow_fb:
                rep.warnings.append(
                    f"realAssetTargets[{idx}] ({label}): 一般対象 ({cat}) は未紐づけですが、手描き小道具代替が可能です。"
                )

    # 台本テキストからの実在人名候補スキャン（一般名詞は手描き小道具許容のためスキャンしない）
    catalog_search_pool: list[tuple[str, str]] = []
    for aid, item in catalog_by_id.items():
        hay = " ".join(
            [
                str(item.get("labelJa") or ""),
                str(item.get("subjectNameJa") or ""),
                " ".join(str(t) for t in (item.get("tags") or [])),
            ]
        )
        catalog_search_pool.append((aid, hay))

    warned_entities: set[str] = set()
    for sh in body_shots:
        cid = str(sh.get("chunkId") or f"shot_{sh.get('shotIndex')}")
        combined_txt = f"{sh.get('narrationJa') or ''} {_join_shot_subtitles(sh)}"
        for ent, _ent_cat in _detect_real_entities(combined_txt):
            if ent in warned_entities:
                continue
            in_targets = any(ent in t or t in ent for t in covered_target_terms if t)
            matched_catalog_ids = [aid for aid, hay in catalog_search_pool if ent in hay]
            used_here_or_anywhere = any(aid in used_asset_ids for aid in matched_catalog_ids)
            if not (in_targets or (matched_catalog_ids and used_here_or_anywhere)):
                warned_entities.add(ent)
                rep.warnings.append(
                    f"{cid}: 台本内の実在人物候補 {ent!r} に本人実写素材（assetCatalog / realAssetTargets）が紐づいていません。"
                )

    rep.metrics = {
        "compositionId": comp_id,
        "body_shots": len(body_shots),
        "tsx_scene_shots": tsx_scene_shots,
        "media_backdrop_shots": media_backdrop_shots,
        "max_visual_static_gap_sec": round(max_static_gap_sec, 2),
        "unique_polarities": sorted(unique_polarities),
        "polarity_switches": polarity_switches,
        "backdrop_switches": backdrop_switches,
        "asset_catalog_count": len(catalog_by_id),
        "used_asset_count": len(used_asset_ids),
        "real_asset_targets_count": len(real_targets),
        "end_cta_enabled": bool(isinstance(end_cta, dict) and end_cta.get("enabled", True) is not False),
        "audio_mode": audio.get("mode") if isinstance(audio, dict) else None,
        "total_sfx": total_sfx,
        "chapter_eyecatches": len(spec_eyecatch_by_chapter),
        "spec_long_text_warnings": spec_long_text_warnings,
        "tsx_low_cue_density_warnings": low_cue_density_warnings,
    }

    if tsx_rep is not None:
        clean_tsx_metrics = {
            k: v for k, v in tsx_rep.metrics.items() if not k.startswith("_")
        }
        rep.metrics.update(clean_tsx_metrics)

    return rep


def format_validation_report(report: ValidationReport, title: str = "Stickman Collage Validation") -> str:
    lines = [
        f"=== {title} ===",
        f"判定: {'PASSED' if report.passed else 'FAILED'} (Errors: {len(report.errors)}, Warnings: {len(report.warnings)})",
    ]
    if report.metrics:
        m = report.metrics
        lines.append(
            "メトリクス: "
            f"compId={m.get('compositionId', '-')}, "
            f"body={m.get('body_shots', '-')}, "
            f"tsx_scenes={m.get('tsx_scene_shots', 0)}, "
            f"max_static_gap={m.get('max_visual_static_gap_sec', '-')}s, "
            f"polarities={m.get('unique_polarities', [])} (switches={m.get('polarity_switches', 0)}), "
            f"assets={m.get('used_asset_count', 0)}/{m.get('asset_catalog_count', 0)}, "
            f"real_targets={m.get('real_asset_targets_count', 0)}, "
            f"audio={m.get('audio_mode', '-')}, "
            f"sfx={m.get('total_sfx', 0)} (tsx_cues={m.get('tsx_sfx_cue_count', 0)}), "
            f"endCta={m.get('end_cta_enabled', False)}"
        )
    if report.errors:
        lines.append("[ERRORS]")
        for e in report.errors:
            lines.append(f"  - {e}")
    if report.warnings:
        lines.append("[WARNINGS]")
        for w in report.warnings:
            lines.append(f"  - {w}")
    return "\n".join(lines)
