/** 1 ファイル分のソースを監査する（コメント行は対象外）。 */
export function auditPlanESource(text: string, file = '<inline>'): PlanESourceIssue[] {
  const issues: PlanESourceIssue[] = [];
  const lines = text.split(/\r?\n/);
  const generatedTimeline = lines[0] === '// Auto-generated by pipeline/scripts/build_plan_e_assets.py';
  let inBlockComment = false;
  lines.forEach((raw, idx) => {
    let line = raw;
    if (inBlockComment) {
      const end = line.indexOf('*/');
      if (end === -1) return;
      line = line.slice(end + 2);
      inBlockComment = false;
    }
    const blockStart = line.indexOf('/*');
    if (blockStart !== -1 && line.indexOf('*/', blockStart) === -1) {
      inBlockComment = true;
      line = line.slice(0, blockStart);
    }
    line = line.replace(/\/\*.*?\*\//g, '').replace(/(^|[^:])\/\/.*$/, '$1');
    if (!line.trim()) return;
    // 生成マニフェストに記録する出典URL。描画コードや同じ行の式は引き続き監査する。
    if (generatedTimeline && /^\s*"sourceUrl":\s*"https?:\/\/[^"\\]+",?\s*$/.test(line)) return;
    for (const rule of SOURCE_RULES) {
      if (rule.re.test(line)) {
        issues.push({
          severity: rule.severity,
          code: rule.code,
          file,
          line: idx + 1,
          excerpt: raw.trim().slice(0, 140),
          message: rule.message,
        });
      }
    }
  });
  return issues;
}
